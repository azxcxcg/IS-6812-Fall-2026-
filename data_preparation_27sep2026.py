"""## Processing Supplementary Tables

This section focuses on processing the supplementary datasets (`bureau.csv`, `bureau_balance.csv`, `previous_application.csv`) to extract aggregated features. These features will then be merged with the main `app_train_processed` and `app_test_processed` dataframes to provide a more comprehensive view of the applicants' credit history and past interactions with Home Credit or other financial institutions. The goal is to create consistent features across both train and test sets.
"""

class SupplementaryProcessor:
    """
    A class to process and aggregate supplementary tables (bureau, bureau_balance, previous_application)
    and prepare them for merging with the main application data.
    """
    def __init__(self, data_path='/content/drive/MyDrive/MSBA Practice Project/'):
        self.data_path = data_path
        self.bureau = None
        self.bureau_balance = None
        self.previous_application = None
        self.bureau_aggregations = {}
        self.prev_app_aggregations = {}

    def _load_data(self):
        """
        Loads the supplementary datasets.
        """
        print("Loading supplementary data...")
        self.bureau = pd.read_csv(self.data_path + 'bureau.csv')
        self.bureau_balance = pd.read_csv(self.data_path + 'bureau_balance.csv')
        self.previous_application = pd.read_csv(self.data_path + 'previous_application.csv')
        print("Supplementary data loaded.")

    def _process_bureau_and_balance(self):
        """
        Processes bureau and bureau_balance tables.
        - One-hot encodes categorical features in bureau_balance.
        - Aggregates bureau_balance by SK_ID_BUREAU.
        - Merges aggregated bureau_balance into bureau.
        - One-hot encodes categorical features in bureau.
        - Aggregates bureau by SK_ID_CURR.
        """
        print("Processing Bureau and Bureau Balance data...")

        # --- Process bureau_balance ---
        # One-hot encode categorical features
        bb_categorical_cols = self.bureau_balance.select_dtypes('object').columns
        self.bureau_balance = pd.get_dummies(self.bureau_balance, columns=bb_categorical_cols, dummy_na=False)

        # Group by SK_ID_BUREAU and aggregate
        bb_aggregations = {
            'MONTHS_BALANCE': ['min', 'max', 'size'],
            **{col: ['mean'] for col in self.bureau_balance.columns if '_STATUS' in col}
        }
        bureau_by_loan = self.bureau_balance.groupby('SK_ID_BUREAU').agg(bb_aggregations)
        bureau_by_loan.columns = ['_'.join(col).strip() for col in bureau_by_loan.columns.values]

        # Merge with bureau
        self.bureau = self.bureau.merge(bureau_by_loan, on='SK_ID_BUREAU', how='left')
        self.bureau.drop(columns=['SK_ID_BUREAU'], inplace=True) # SK_ID_BUREAU is no longer needed after aggregation

        # --- Process bureau ---
        # One-hot encode categorical features
        bureau_categorical_cols = self.bureau.select_dtypes('object').columns
        self.bureau = pd.get_dummies(self.bureau, columns=bureau_categorical_cols, dummy_na=False)

        # Define aggregations for bureau
        bureau_aggregations = {
            'DAYS_CREDIT': ['min', 'max', 'mean', 'var'],
            'DAYS_CREDIT_ENDDATE': ['min', 'max', 'mean'],
            'DAYS_ENDDATE_FACT': ['min', 'max', 'mean'],
            'AMT_CREDIT_MAX_OVERDUE': ['max', 'mean'],
            'CNT_CREDIT_PROLONG': ['sum'],
            'AMT_CREDIT_SUM': ['max', 'mean', 'sum'],
            'AMT_CREDIT_SUM_DEBT': ['max', 'mean', 'sum'],
            'AMT_CREDIT_SUM_OVERDUE': ['mean'],
            'AMT_CREDIT_SUM_LIMIT': ['mean', 'sum'],
            'AMT_ANNUITY': ['max', 'mean', 'sum'],
            'DAYS_EMPLOYED': ['mean'], # Use days employed from bureau for a new feature
            'CREDIT_DAY_OVERDUE': ['max', 'mean'],
            'SK_ID_CURR': ['count'] # To count number of previous credits
        }
        for col in self.bureau.columns:
            if 'CREDIT_TYPE_' in col or 'CREDIT_ACTIVE_' in col or '_STATUS_' in col:
                bureau_aggregations[col] = ['mean']

        self.bureau_aggregations = self.bureau.groupby('SK_ID_CURR').agg(bureau_aggregations)
        self.bureau_aggregations.columns = ['bureau_' + '_'.join(col).strip() for col in self.bureau_aggregations.columns.values]

        print("Bureau and Bureau Balance data processed.")
        return self.bureau_aggregations

    def _process_previous_application(self):
        """
        Processes previous_application table.
        - One-hot encodes categorical features.
        - Aggregates by SK_ID_CURR.
        """
        print("Processing Previous Application data...")

        # One-hot encode categorical features
        prev_app_categorical_cols = self.previous_application.select_dtypes('object').columns
        self.previous_application = pd.get_dummies(self.previous_application, columns=prev_app_categorical_cols, dummy_na=False)

        # Define aggregations for previous_application
        prev_app_aggregations = {
            'AMT_ANNUITY': ['min', 'max', 'mean'],
            'AMT_APPLICATION': ['min', 'max', 'mean'],
            'AMT_CREDIT': ['min', 'max', 'mean'],
            'AMT_GOODS_PRICE': ['min', 'max', 'mean'],
            'HOUR_APPR_PROCESS_START': ['min', 'max', 'mean'],
            'RATE_DOWN_PAYMENT': ['min', 'max', 'mean'],
            'DAYS_DECISION': ['min', 'max', 'mean'],
            'CNT_PAYMENT': ['mean', 'sum'],
            'SK_ID_CURR': ['count'] # Count number of previous applications
        }
        for col in self.previous_application.columns:
            if 'NAME_CONTRACT_STATUS' in col or 'NAME_YIELD_GROUP' in col or 'PRODUCT_COMBINATION' in col:
                prev_app_aggregations[col] = ['mean']

        self.prev_app_aggregations = self.previous_application.groupby('SK_ID_CURR').agg(prev_app_aggregations)
        self.prev_app_aggregations.columns = ['prev_app_' + '_'.join(col).strip() for col in self.prev_app_aggregations.columns.values]

        print("Previous Application data processed.")
        return self.prev_app_aggregations

    def transform(self, app_train_df, app_test_df):
        """
        Orchestrates the processing of supplementary tables and merges them with application data.
        """
        self._load_data()

        bureau_features = self._process_bureau_and_balance()
        prev_app_features = self._process_previous_application()

        print("Merging supplementary features with application data...")

        # Merge with training data
        app_train_df = app_train_df.merge(bureau_features, on='SK_ID_CURR', how='left')
        app_train_df = app_train_df.merge(prev_app_features, on='SK_ID_CURR', how='left')

        # Merge with test data
        app_test_df = app_test_df.merge(bureau_features, on='SK_ID_CURR', how='left')
        app_test_df = app_test_df.merge(prev_app_features, on='SK_ID_CURR', how='left')

        # Fill NaNs created by merges (for new aggregated features) with 0 or an appropriate value
        # A common strategy is to fill NaNs from aggregated counts/sums with 0, as it means no such record existed.
        # For other numerical aggregates (mean, min, max, var), median/mean imputation might be more appropriate
        # but for simplicity for newly added features, 0 often makes sense if it implies 'absence of activity'.
        # Here, we'll fill numerical NaNs with 0 in the new columns.
        new_bureau_cols = [col for col in bureau_features.columns if col not in app_train_df.columns]
        for col in new_bureau_cols:
            if col in app_train_df.columns and app_train_df[col].dtype in ['float64', 'int64']:
                app_train_df[col].fillna(0, inplace=True)
            if col in app_test_df.columns and app_test_df[col].dtype in ['float64', 'int64']:
                app_test_df[col].fillna(0, inplace=True)

        new_prev_app_cols = [col for col in prev_app_features.columns if col not in app_train_df.columns]
        for col in new_prev_app_cols:
            if col in app_train_df.columns and app_train_df[col].dtype in ['float64', 'int64']:
                app_train_df[col].fillna(0, inplace=True)
            if col in app_test_df.columns and app_test_df[col].dtype in ['float64', 'int64']:
                app_test_df[col].fillna(0, inplace=True)

        print("Supplementary features merged.")
        return app_train_df, app_test_df