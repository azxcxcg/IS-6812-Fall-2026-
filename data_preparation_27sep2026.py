class DataProcessor:
    """
    A class for cleaning, transforming, and engineering features for the Home Credit Default Risk dataset.

    The methods in this class are designed to ensure consistency between training and test datasets
    by fitting parameters (e.g., imputation values, columns to drop) on the training data only
    and then applying them to both. The decisions are based on the preceding EDA.
    """
    def __init__(self, high_missing_threshold=0.70):
        self.imputation_values = {}  # Stores median/mode for numerical/categorical imputation
        self.dropped_columns = []    # Stores columns identified to be dropped due to high missing % in train
        self.categorical_cols_with_missing_category = [
            'NAME_TYPE_SUITE', 'OCCUPATION_TYPE', 'FONDKAPREMONT_MODE',
            'HOUSETYPE_MODE', 'WALLSMATERIAL_MODE', 'EMERGENCYSTATE_MODE'
        ] # Categorical columns where 'Missing' will be a new category, based on EDA inspection
        self.high_missing_threshold = high_missing_threshold

    def _handle_xna_gender(self, df):
        """
        EDA Decision: Replaces 'XNA' values in 'CODE_GENDER' with NaN.
        """
        if 'CODE_GENDER' in df.columns:
            df['CODE_GENDER'] = df['CODE_GENDER'].replace('XNA', np.nan)
        return df

    def _handle_days_employed_outlier(self, df):
        """
        EDA Decision: Addresses the 365243 outlier in 'DAYS_EMPLOYED'.
        This value is an anomaly indicating an undocumented employment status.
        It's replaced with NaN, and a binary flag 'DAYS_EMPLOYED_ANOM' is created.
        """
        if 'DAYS_EMPLOYED' in df.columns:
            df['DAYS_EMPLOYED_ANOM'] = (df['DAYS_EMPLOYED'] == 365243).astype(int)
            df['DAYS_EMPLOYED'] = df['DAYS_EMPLOYED'].replace({365243: np.nan}) # Removed inplace=True
        return df

    def _drop_high_missing_columns(self, df):
        """
        EDA Decision: Drops columns with a very high percentage of missing values (defined by threshold).
        Columns to drop are identified during the `fit` phase on the training data.
        """
        if self.dropped_columns:
            df = df.drop(columns=self.dropped_columns, errors='ignore')
        return df

    def _create_missing_indicators(self, df):
        """
        EDA Decision: Creates binary indicators for columns that originally had missing values.
        This is done before imputation to capture the initial missingness.
        """
        # Ensure we only create indicators for columns that exist in the current df
        # and were identified as missing in the training data.
        for col in list(self.imputation_values.keys()): # Keys represent columns that had missing values in train
            if col in df.columns:
                # Only create indicator if the column still has NaNs before imputation
                # (e.g., if XNA was converted to NaN or original NaNs exist)
                if df[col].isnull().any():
                    df[col + '_IS_MISSING'] = df[col].isnull().astype(int)
        # Special handling for CODE_GENDER if it became NaN from XNA
        if 'CODE_GENDER' in df.columns and 'CODE_GENDER' not in self.dropped_columns and df['CODE_GENDER'].isnull().any():
             df['CODE_GENDER_IS_MISSING'] = df['CODE_GENDER'].isnull().astype(int)
        return df

    def _impute_missing_values(self, df):
        """
        EDA Decision: Imputes missing values using strategies determined during the `fit` phase.
        Numerical columns are imputed with the median; specific categorical columns get 'Missing'; others by mode.
        """
        for col in df.columns:
            if col in self.imputation_values: # Only impute for columns that had missing values in train
                if df[col].dtype in ['int64', 'float64']:
                    df[col] = df[col].fillna(self.imputation_values[col]) # Removed inplace=True
                elif df[col].dtype == 'object':
                    if col in self.categorical_cols_with_missing_category:
                        df[col] = df[col].fillna('Missing') # Removed inplace=True
                    else:
                        df[col] = df[col].fillna(self.imputation_values[col]) # Removed inplace=True
        return df

    def _engineer_demographic_features(self, df):
        """
        EDA Decision: Updates demographic features like age and employment duration.
        'DAYS_BIRTH' and 'DAYS_EMPLOYED' (after outlier handling) are converted to positive years.
        """
        if 'DAYS_BIRTH' in df.columns:
            df['AGE_YEARS'] = df['DAYS_BIRTH'] / -365
        if 'DAYS_EMPLOYED' in df.columns:
            df['EMPLOYMENT_YEARS'] = df['DAYS_EMPLOYED'] / -365
        return df

    def _engineer_financial_ratios(self, df):
        """
        EDA Decision: Adds financial ratios based on income, credit, and annuity amounts.
        """
        # Using a temporary copy for ratio calculations to prevent SettingWithCopyWarning
        # and ensure original columns are not modified unexpectedly within this method.
        temp_df_for_ratios = df.copy()

        if all(col in temp_df_for_ratios.columns for col in ['AMT_CREDIT', 'AMT_INCOME_TOTAL']):
            df['CREDIT_INCOME_RATIO'] = temp_df_for_ratios['AMT_CREDIT'] / temp_df_for_ratios['AMT_INCOME_TOTAL']
        if all(col in temp_df_for_ratios.columns for col in ['AMT_ANNUITY', 'AMT_INCOME_TOTAL']):
            df['ANNUITY_INCOME_RATIO'] = temp_df_for_ratios['AMT_ANNUITY'] / temp_df_for_ratios['AMT_INCOME_TOTAL']
        if all(col in temp_df_for_ratios.columns for col in ['AMT_CREDIT', 'AMT_ANNUITY']):
            df['CREDIT_ANNUITY_RATIO'] = temp_df_for_ratios['AMT_CREDIT'] / temp_df_for_ratios['AMT_ANNUITY']
        if all(col in temp_df_for_ratios.columns for col in ['AMT_GOODS_PRICE', 'AMT_CREDIT']):
            df['GOODS_PRICE_CREDIT_RATIO'] = temp_df_for_ratios['AMT_GOODS_PRICE'] / temp_df_for_ratios['AMT_CREDIT']
        if all(col in temp_df_for_ratios.columns for col in ['AMT_INCOME_TOTAL', 'CNT_FAM_MEMBERS']):
            df['INCOME_PER_PERSON'] = temp_df_for_ratios['AMT_INCOME_TOTAL'] / temp_df_for_ratios['CNT_FAM_MEMBERS']
            # Handle potential division by zero if CNT_FAM_MEMBERS is 0 after imputation (unlikely but good practice)
            df['INCOME_PER_PERSON'] = df['INCOME_PER_PERSON'].replace([np.inf, -np.inf], np.nan) # Removed inplace=True
            df['INCOME_PER_PERSON'] = df['INCOME_PER_PERSON'].fillna(df['AMT_INCOME_TOTAL']) # If members is 0, income per person is total income, Removed inplace=True
        return df

    def _create_binned_features(self, df):
        """
        EDA Decision: Creates binned features for 'AGE_YEARS' and 'CNT_CHILDREN'.
        """
        if 'AGE_YEARS' in df.columns:
            df['AGE_GROUP'] = pd.cut(df['AGE_YEARS'], bins=[0, 25, 35, 45, 55, 65, 100],
                                     labels=['<25', '25-34', '35-44', '45-54', '55-64', '65+'], right=False)
        if 'CNT_CHILDREN' in df.columns:
            df['CHILDREN_GROUP'] = pd.cut(df['CNT_CHILDREN'], bins=[-1, 0, 1, 2, df['CNT_CHILDREN'].max() + 1],
                                          labels=['No Children', '1 Child', '2 Children', '3+ Children'], right=True)
        return df

    def fit(self, X_train):
        """
        Fits the processor on the training data to learn parameters for transformations.
        This includes identifying columns to drop and calculating imputation values.
        """
        temp_df = X_train.copy() # Work on a copy to avoid modifying original during fit

        # 1. Handle specific outliers/conversions first
        temp_df = self._handle_xna_gender(temp_df)
        temp_df = self._handle_days_employed_outlier(temp_df)

        # 2. Identify columns to drop based on training data's missing percentage
        missing_percentage = temp_df.isnull().sum() * 100 / len(temp_df)
        self.dropped_columns = missing_percentage[missing_percentage > self.high_missing_threshold].index.tolist()

        # 3. Apply dropping *before* computing imputation values, to avoid using dropped columns
        temp_df = self._drop_high_missing_columns(temp_df)

        # 4. Compute and store imputation values for remaining columns
        for col in temp_df.columns:
            if temp_df[col].isnull().any():
                if temp_df[col].dtype in ['int64', 'float64']:
                    self.imputation_values[col] = temp_df[col].median()
                elif temp_df[col].dtype == 'object' and col not in self.categorical_cols_with_missing_category:
                    self.imputation_values[col] = temp_df[col].mode()[0] # Only for categorical not handled by 'Missing' category
        return self

    def transform(self, df):
        """
        Applies the learned transformations to a DataFrame (train or test).
        """
        df = df.copy()

        # Apply cleaning steps
        df = self._handle_xna_gender(df)
        df = self._handle_days_employed_outlier(df)
        df = self._drop_high_missing_columns(df) # Drop columns identified during fit

        # Create missing indicators before imputation
        df = self._create_missing_indicators(df)

        # Impute missing values using stored values from training data
        df = self._impute_missing_values(df)

        # Apply feature engineering steps
        df = self._engineer_demographic_features(df)
        df = self._engineer_financial_ratios(df) # Pass df directly, logic inside handles copying
        df = self._create_binned_features(df)

        return df

    def fit_transform(self, X_train):
        """
        Fits the processor on training data and then transforms it.
        """
        return self.fit(X_train).transform(X_train)

